// The periods a student can rename. Change this if the school adds or drops a period.
export const PERIOD_NUMBERS = [1, 2, 3, 4, 5, 6, 7];

// "Period 3" -> "3". Returns null for anything that isn't a numbered period
// (SMART period, lunch, passing period...), so those never get renamed.
export const getPeriodNumber = (periodName) => {
  const match = /^\s*(?:period|pd\.?)\s*(\d+)\s*$/i.exec(periodName || "");
  return match ? String(Number(match[1])) : null;
};

// The class the user picked for this period, or null if they haven't picked one.
export const getPeriodClass = (periodName, periodClasses) => {
  const number = getPeriodNumber(periodName);
  if (!number || !periodClasses) return null;
  return periodClasses[number] || null;
};

// What to show for a period: the user's class if they set one, otherwise the original name.
export const getPeriodLabel = (periodName, periodClasses) =>
  getPeriodClass(periodName, periodClasses) || periodName;
